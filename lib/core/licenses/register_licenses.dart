import 'dart:convert';

import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';

import '../constants/app_constants.dart';

/// The Rust crates of Bag's Tor library and the C sources bundled in them.
const rustLicensesAsset = 'assets/licenses/rust_licenses.json';

/// The Android libraries the app and its plugins pull in.
const nativeLicensesAsset = 'assets/licenses/native_licenses.json';

/// Adds the licence notices Flutter doesn't collect to [LicenseRegistry], so
/// the licence page lists everything Bag ships. Flutter already registers
/// every Dart package and its own engine; these are the Rust crates compiled
/// into the tor plugin's native library (and the C sources bundled in them)
/// and the Android libraries. Both assets are generated by
/// tools/licenses/generate.sh, which also writes THIRD_PARTY_NOTICES.md.
///
/// Only what this build contains is listed: crates built for this platform,
/// Android libraries on Android, and the Google Play-only libraries only in
/// the store flavor. The Rust standard library, and any font Bag ships, are
/// listed on both platforms. Each package appears in one entry. Nothing is read
/// until the licence page asks for the licences.
///
/// Call once, before `runApp`.
void registerThirdPartyLicenses({
  @visibleForTesting AssetBundle? bundle,
  @visibleForTesting TargetPlatform? platform,
  @visibleForTesting String? flavor,
}) {
  LicenseRegistry.addLicense(
    () => _thirdPartyLicenses(
      bundle ?? rootBundle,
      platform ?? defaultTargetPlatform,
      flavor ?? AppConstants.kFlavor,
    ),
  );
}

Stream<LicenseEntry> _thirdPartyLicenses(
  AssetBundle bundle,
  TargetPlatform platform,
  String flavor,
) async* {
  final rust = await _load(bundle, rustLicensesAsset);
  yield* Stream.fromIterable(_rustEntries(rust, platform));
  final native = await _load(bundle, nativeLicensesAsset);
  if (platform == TargetPlatform.android) {
    yield* Stream.fromIterable(
      _androidEntries(native, includeStore: flavor == 'store'),
    );
  }
  yield* Stream.fromIterable(_fontEntries(native));
}

Future<Map<String, dynamic>> _load(AssetBundle bundle, String asset) async =>
    jsonDecode(await bundle.loadString(asset, cache: false))
        as Map<String, dynamic>;

/// Whether a crate built for [targets] is in this platform's build. On a
/// platform Bag doesn't ship, everything is listed.
bool _builtFor(List<dynamic> targets, TargetPlatform platform) =>
    switch (platform) {
      TargetPlatform.android => targets.any(
        (t) => (t as String).contains('-android'),
      ),
      TargetPlatform.iOS => targets.any(
        (t) => (t as String).endsWith('-apple-ios'),
      ),
      _ => true,
    };

/// One entry per crate name (all its versions, each licence text once), and
/// one per bundled C library.
Iterable<LicenseEntry> _rustEntries(
  Map<String, dynamic> rust,
  TargetPlatform platform,
) sync* {
  final texts = (rust['texts'] as List).cast<String>();
  final byPackage = <String, List<Map<String, dynamic>>>{};
  for (final crate in (rust['crates'] as List).cast<Map<String, dynamic>>()) {
    if (!_builtFor(crate['targets'] as List, platform)) continue;
    final package = (crate['package'] ?? crate['name']) as String;
    byPackage.putIfAbsent(package, () => []).add(crate);
  }
  for (final MapEntry(key: package, value: crates) in byPackage.entries) {
    final paragraphs = <String>[];
    final shown = <int>{};
    for (final crate in crates) {
      final terms = crate['license'] == crate['expression']
          ? crate['license']
          : '${crate['expression']}, used under ${crate['license']}';
      paragraphs.add(
        'Rust crate ${crate['name']} ${crate['version']}, in Bag\'s Tor '
        'library. Licence: $terms.',
      );
      if (crate['source'] != null) paragraphs.add('Source: ${crate['source']}');
      for (final note in (crate['notes'] as List? ?? const [])) {
        paragraphs.add(note as String);
      }
      for (final text in [
        ...crate['licenses'] as List,
        ...(crate['notices'] as List? ?? const []),
      ]) {
        final index = text['text'] as int;
        if (shown.add(index)) paragraphs.add(texts[index]);
      }
    }
    yield LicenseEntryWithLineBreaks([package], paragraphs.join('\n\n'));
  }
  // The Rust standard library, linked into the library on every target.
  for (final item in (rust['toolchain'] as List).cast<Map<String, dynamic>>()) {
    yield LicenseEntryWithLineBreaks(
      ['${item['name']}'],
      [
        '${item['name']} ${item['version']}, in Bag\'s Tor library. Licence: '
            '${item['expression']}, used under ${item['license']}.',
        ...(item['notes'] as List).cast<String>(),
        for (final licence in item['licenses'] as List)
          texts[licence['text'] as int],
      ].join('\n\n'),
    );
  }
  for (final item in (rust['bundled'] as List).cast<Map<String, dynamic>>()) {
    if (!_builtFor(item['targets'] as List, platform)) continue;
    final terms = item['expression'] == null
        ? item['license']
        : '${item['expression']}, used under ${item['license']}';
    yield LicenseEntryWithLineBreaks(
      ['${item['name']}'],
      [
        '${item['name']} ${item['version']}, C sources bundled in the Rust '
            'crate ${item['in_crate']} and compiled into Bag\'s Tor library. '
            'Licence: $terms. ${item['homepage']}',
        for (final licence in item['licenses'] as List)
          texts[licence['text'] as int],
      ].join('\n\n'),
    );
  }
}

/// One entry per Maven group: each library with its version and licence,
/// then each licence text once. Proprietary libraries (store flavor only)
/// name their terms instead.
Iterable<LicenseEntry> _androidEntries(
  Map<String, dynamic> native, {
  required bool includeStore,
}) sync* {
  final texts = (native['texts'] as Map).cast<String, String>();
  final terms = (native['terms'] as Map).cast<String, dynamic>();
  final byGroup = <String, List<Map<String, dynamic>>>{};
  for (final library
      in (native['libraries'] as List).cast<Map<String, dynamic>>()) {
    if (library['flavor'] == 'store' && !includeStore) continue;
    final group = (library['coordinate'] as String).split(':').first;
    byGroup.putIfAbsent(group, () => []).add(library);
  }
  for (final MapEntry(key: group, value: libraries) in byGroup.entries) {
    final lines = <String>[];
    final textKeys = <String>{};
    for (final library in libraries) {
      final term = library['terms'] == null
          ? null
          : terms[library['terms']] as Map<String, dynamic>;
      final licence = term == null
          ? library['license']
          : '${term['name']} (proprietary), ${term['url']}';
      final storeOnly =
          library['flavor'] == 'store' ? ', in the Google Play build only' : '';
      lines.add(
        '${library['coordinate']} ${library['version']}: $licence$storeOnly.',
      );
      if (library['source'] != null) {
        lines.add('    Source: ${library['source']}');
      }
      if (library['text'] != null) textKeys.add(library['text'] as String);
      for (final item in (library['embedded'] as List? ?? const [])) {
        lines.add('    Contains ${item['name']}: ${item['license']}.');
        textKeys.add(item['text'] as String);
      }
    }
    yield LicenseEntryWithLineBreaks(
      [group],
      [
        'Android libraries in Bag:',
        ...lines,
        for (final key in textKeys) texts[key]!,
      ].join('\n\n'),
    );
  }
}

/// Fonts Bag ships, each with its licence: today the Material Icons font
/// Flutter bundles (the sat symbol is drawn, not a font).
Iterable<LicenseEntry> _fontEntries(Map<String, dynamic> native) sync* {
  for (final font in (native['fonts'] as List).cast<Map<String, dynamic>>()) {
    final notice = (font['notice'] as String? ?? '').isEmpty
        ? ''
        : ' ${font['notice']}.';
    final link = (font['link'] as String? ?? '').isEmpty
        ? ''
        : ' ${font['link']}';
    yield LicenseEntryWithLineBreaks(
      ['${font['package'] ?? font['name']}'],
      '${font['name']}, font file ${font['asset']}.$notice Licence: '
      '${font['license']}.$link\n\n${font['text']}',
    );
  }
}
